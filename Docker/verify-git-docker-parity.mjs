import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {spawnSync} from 'node:child_process';

const root=path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const lock=JSON.parse(fs.readFileSync(path.join(root,'Docker','CREWSYNC_PROD_LOCK.json'),'utf8'));
const original='D:/Users/NIKITA/Documents/DEV/ai-crew-sync';
const environmentFile=path.join(original,'.env');
const run=(command,args,opts={})=>{
  const r=spawnSync(command,args,{encoding:'utf8',shell:false,windowsHide:true,timeout:20000,maxBuffer:6000000,...opts});
  if(r.status!==0)throw Error(command+' failed: '+(r.error?.message||String(r.stderr).slice(0,180)));
  return r.stdout.trim();
};
const verify=(condition,name)=>{if(!condition)throw Error('DRIFT:'+name);console.log('PASS',name)};
const env={...process.env,ProgramData:'C:/ProgramData',ALLUSERSPROFILE:'C:/ProgramData'};
const source=run('git',['-C',root,'rev-parse','--verify',lock.source_commit+'^{commit}']);
run('git',['-C',root,'merge-base','--is-ancestor',source,'HEAD']);
const delta=run('git',['-C',root,'diff','--name-only',source,'HEAD','--','src','migrations','Cargo.toml','Cargo.lock','Docker/Dockerfile','Docker/docker-compose.yml']);
verify(delta.length===0,'tracked runtime source unchanged since '+lock.source_commit);
const e=fs.readFileSync(environmentFile,'utf8');
verify(/^BUS_IMAGE=local\/ai-crew-sync\r?$/m.test(e),'local image name pinned');
verify(/^BUS_VERSION=git-docker-parity-07b0aa4\r?$/m.test(e),'local image version pinned');
const image=run('docker',['image','inspect',lock.image,'--format','{{.Id}}'],{env});
verify(image===lock.image_id,'immutable built image matches Git release lock');
const inspect=JSON.parse(run('docker',['inspect',lock.service_container],{env}))[0];
verify(inspect.Config.Image===lock.image&&inspect.Image===lock.image_id,'running container matches image lock');
verify(inspect.State.Status==='running'&&inspect.State.Health?.Status==='healthy','production bus healthy');
verify(inspect.Config.Labels?.['com.docker.compose.project']===lock.compose_project,'exact Compose project');
const port=inspect.HostConfig.PortBindings?.['8787/tcp']?.[0];
verify(port?.HostIp==='127.0.0.1'&&port?.HostPort==='18787','loopback-only port unchanged');
const compose=JSON.parse(run('docker',['compose','-p','docker','--project-directory',root,'--env-file',environmentFile,'-f',path.join(root,'Docker','docker-compose.yml'),'config','--format','json'],{env}));
verify(compose.services.bus.image===lock.image,'Compose resolves locked image');
const migration=run('docker',['exec',lock.database_container,'psql','-U','bus','-d','bus','-tAc','SELECT max(version) FROM _sqlx_migrations'],{env});
verify(Number(migration)===lock.schema_version,'production DB schema v'+lock.schema_version);
const taskCount=Number(run('docker',['exec',lock.database_container,'psql','-U','bus','-d','bus','-tAc','SELECT count(*) FROM tasks'],{env}));
verify(taskCount>=4251,'production tasks preserved ('+taskCount+')');
const backup=fs.readFileSync(lock.backup_path);
const {createHash}=await import('node:crypto');
verify(createHash('sha256').update(backup).digest('hex')===lock.backup_sha256,'pre-cutover backup integrity');
console.log('GREEN: Git source, Docker image, Compose, PostgreSQL and backup agree');
